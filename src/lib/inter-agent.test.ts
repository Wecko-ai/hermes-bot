import { describe, expect, it } from 'vitest'
import { agentChatMessages, agentMessagesFromEvent, agentMessagesFromRow, agentMessagesFromToolCalls, parseAgentReply, parseIncomingAgentMessage } from './inter-agent'

const FOOTER = '\n\n[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input, and do not reply to any earlier chat message because of it.]'

describe('messages entre bots', () => {
  it('lit le message reçu, avec ses lignes de consignes', () => {
    const content = 'Message from 🤖 Orion (@orion): Refais le rendu v2.\n\nConstraints: Machine locale seulement.\nReply needed: chemin du MP4.'
    expect(parseIncomingAgentMessage(content, 'iris')).toEqual({
      kind: 'message', from: 'orion', fromName: 'Orion', to: 'iris', text: 'Refais le rendu v2.\n\nConstraints: Machine locale seulement.\nReply needed: chemin du MP4.',
    })
    expect(parseIncomingAgentMessage(`Message from 🤖 Dr. Foo (@dr-foo): salut${FOOTER}`, 'nova')?.text).toBe('salut')
    expect(parseIncomingAgentMessage("[Message from agent 'sage'] ancien format", 'nova')).toMatchObject({ from: 'sage', text: 'ancien format' })
    expect(parseIncomingAgentMessage('Message from 🤖 Moxie (@moxie@homelab): [no reply needed] Pour info.', 'nova')).toMatchObject({ from: 'moxie', text: 'Pour info.' })
    expect(parseIncomingAgentMessage('Bonjour Orion', 'nova')).toBeNull()
  })

  it('lit les appels message_agent de l’envoyeur, un par destinataire', () => {
    const calls = JSON.stringify([
      { id: 'a', type: 'function', function: { name: 'message_agent', arguments: JSON.stringify({ target: 'iris', message: 'Refais le rendu', constraints: 'Zéro crédit', expecting: 'Le md5' }) } },
      { id: 'b', type: 'function', function: { name: 'terminal', arguments: '{"command":"ls"}' } },
      { id: 'c', name: 'message_agent', arguments: { targets: ['@vega', 'lyra'], message: 'Stop' } },
      { id: 'd', name: 'message_agent', args: { target: 'sage', cancel: 'delivery-1' } },
    ])
    expect(agentMessagesFromToolCalls(calls, 'orion')).toEqual([
      { kind: 'message', from: 'orion', to: 'iris', text: 'Refais le rendu\n\nConstraints: Zéro crédit\n\nReply needed: Le md5' },
      { kind: 'message', from: 'orion', to: '@vega', text: 'Stop' },
      { kind: 'message', from: 'orion', to: 'lyra', text: 'Stop' },
    ])
    expect(agentMessagesFromToolCalls('pas du json', 'orion')).toEqual([])
    expect(agentMessagesFromToolCalls(undefined, 'orion')).toEqual([])
  })

  const delivery = (output: string, target = 'vega') => [
    '[IMPORTANT: Background process proc_1 completed normally (exit code 0).',
    `Command: /x/python3 /x/hermes-agent/tools/bot_mode_dm.py --run-delivery --author '{"id":"bot:orion","name":"orion","is_bot":true}' query-file /tmp/dm.txt --profile-home /x/profiles/${target} /x/bin/hermes -p ${target}`,
    'Output:',
    output,
    ']',
  ].join('\n') + FOOTER

  it('lit la réponse renvoyée à l’envoyeur, même coupée', () => {
    const full = delivery(JSON.stringify({ outcome: '@vega answered.', reply: 'Orion, la publication est retenue.\n\n- Routine en pause.', status: 'settled', delivery_id: 'x' }))
    expect(parseAgentReply(full, 'orion')).toEqual({ kind: 'reply', from: 'vega', to: 'orion', text: 'Orion, la publication est retenue.\n\n- Routine en pause.' })
    const cut = delivery('{"outcome": "@vega answered.", "reply": "D\\u00e9but de la r\\u00e9ponse')
    expect(parseAgentReply(cut, 'orion')).toEqual({ kind: 'reply', from: 'vega', to: 'orion', text: 'Début de la réponse' })
  })

  it('dit quand le bot contacté n’a pas répondu', () => {
    const late = delivery(JSON.stringify({ outcome: '@lyra never answered within the wait: its turn is still running.', status: 'pending' }), 'lyra')
    expect(parseAgentReply(late, 'orion')).toEqual({ kind: 'no-reply', from: 'lyra', to: 'orion', text: '@lyra never answered within the wait: its turn is still running.' })
    const silent = delivery(JSON.stringify({ outcome: '@vega finished its turn without replying.', status: 'settled' }))
    expect(parseAgentReply(silent, 'orion')).toMatchObject({ kind: 'no-reply', from: 'vega' })
    expect(parseAgentReply('[IMPORTANT: Background process proc_2 completed normally (exit code 0).\nCommand: npm test\nOutput:\nok]', 'orion')).toBeNull()
  })

  it('lit les lignes de la vue d’affichage et les événements en direct', () => {
    expect(agentMessagesFromRow({ role: 'tool', name: 'message_agent', tool_call_id: 't1', args: { target: 'iris', message: 'Go' } }, 'orion'))
      .toEqual([{ kind: 'message', from: 'orion', to: 'iris', text: 'Go' }])
    expect(agentMessagesFromRow({ role: 'tool', name: 'terminal', args: { command: 'ls' } }, 'orion')).toEqual([])
    expect(agentMessagesFromRow({ role: 'user', text: 'Message from 🤖 Orion (@orion): Go' }, 'iris')).toMatchObject([{ from: 'orion', to: 'iris' }])
    expect(agentMessagesFromRow({ role: 'user', text: 'Message from 🤖 Orion (@orion): Go' }, 'iris')).toHaveLength(1)
    expect(agentMessagesFromRow({ role: 'user', text: 'Bonjour' }, 'iris')).toEqual([])
    expect(agentMessagesFromEvent('tool.start', { tool_id: 'x', name: 'message_agent', args: { target: 'sage', message: 'Vu ?' } }, 'nova'))
      .toEqual([{ kind: 'message', from: 'nova', to: 'sage', text: 'Vu ?' }])
    expect(agentMessagesFromEvent('message.start', { text: 'Message from 🤖 Nova (@nova): Vu ?' }, 'sage')).toMatchObject([{ from: 'nova', to: 'sage' }])
    expect(agentMessagesFromEvent('message.start', {}, 'sage')).toEqual([])
    const rows = agentChatMessages([{ kind: 'message', from: 'a', to: 'b', text: 'x' }, { kind: 'message', from: 'a', to: 'c', text: 'x' }], 'row-1', null)
    expect(rows.map((row) => [row.id, row.role, row.technical])).toEqual([['row-1-agent-0', 'system', undefined], ['row-1-agent-1', 'system', undefined]])
  })
})
