/**
 * Messages between bots (Hermes’s `message_agent`). Three traces in a Bot Chat:
 * - on the recipient’s side, the `user` row “Message from 🤖 Orion (@orion): …” dropped by the gateway;
 * - on the sender’s side, the `message_agent` call (`target`, `message`, `constraints`, `expecting`): a
 *   `tool` row with `args` in the display view, `tool_calls` of the `assistant` row in the raw history;
 * - still on the sender’s side, the end of the delivery process (`bot_mode_dm.py --run-delivery`), whose
 *   JSON output carries `outcome` (“@iris answered.”) and `reply`.
 * HermesBot shows them as a single line “Orion messaged Iris”; the text opens on demand.
 */
import type { AgentMessage, ChatMessage } from '../types'

type Json = Record<string, unknown>
const asObject = (value: unknown): Json => (value && typeof value === 'object' && !Array.isArray(value) ? value as Json : {})
const asString = (value: unknown) => typeof value === 'string' ? value : ''

// Same pattern as Hermes Desktop’s `AGENT_MESSAGE_RE` (`thread/user-message.tsx`). A message relayed
// from another machine carries `(@handle@connection)`.
const INCOMING = /^(?:Message from (?:🤖\s*)?([^:\n(]{1,64}?)(?:\s*\(@([a-z0-9][a-z0-9_-]{0,63})(?:@[a-zA-Z0-9][a-zA-Z0-9_-]{0,63})?\))?:\s*|\[Message from agent '([^']{1,64})'\]\s*)([\s\S]*)$/u
const NO_REPLY_NEEDED = /^\[no reply needed\]\s*/
const GATEWAY_FOOTER = /\s*\[INTERNAL NOTIFICATION — generated by the Hermes gateway[^\]]*\]\s*$/

/** Message received from another bot, on the recipient `to`’s side. */
export function parseIncomingAgentMessage(content: string, to: string): AgentMessage | null {
  const match = INCOMING.exec(content.replace(GATEWAY_FOOTER, '').trimStart())
  if (!match) return null
  const name = (match[1] || match[3] || '').trim()
  const from = match[2] || name
  if (!from) return null
  return { kind: 'message', from, fromName: name || undefined, to, text: match[4].replace(NO_REPLY_NEEDED, '').trim() }
}

function parseArguments(value: unknown): Json {
  if (typeof value !== 'string') return asObject(value)
  try { return asObject(JSON.parse(value)) } catch { return {} }
}

/** Recipients of a call: `target` alone, or several (a list, or comma-separated names). */
function targetsOf(args: Json): string[] {
  const raw = args.targets ?? args.target
  const list = Array.isArray(raw) ? raw : typeof raw === 'string' ? raw.split(',') : []
  return list.map((item) => (typeof item === 'string' ? item : asString(asObject(item).target)).trim()).filter(Boolean)
}

/** What the recipient reads: the message, then the lines Hermes adds for `constraints` and `expecting`. */
function sentText(args: Json) {
  const parts = [asString(args.message).trim()]
  const constraints = asString(args.constraints).trim()
  const expecting = asString(args.expecting).trim()
  if (constraints) parts.push(`Constraints: ${constraints}`)
  if (expecting) parts.push(`Reply needed: ${expecting}`)
  return parts.filter(Boolean).join('\n\n')
}

/** `message_agent` calls on the sender `from`’s side: OpenAI format (`function.arguments`) or flat (`name`, `args`). */
export function agentMessagesFromToolCalls(toolCalls: unknown, from: string): AgentMessage[] {
  const calls = typeof toolCalls === 'string' ? (() => { try { return JSON.parse(toolCalls) } catch { return [] } })() : toolCalls
  if (!Array.isArray(calls)) return []
  return calls.flatMap((value) => {
    const call = asObject(value)
    const fn = asObject(call.function)
    if ((asString(fn.name) || asString(call.name)) !== 'message_agent') return []
    const args = parseArguments(fn.arguments ?? call.arguments ?? call.args)
    // `cancel` withdraws a pending message: nothing is sent.
    if (args.cancel) return []
    const text = sentText(args)
    return targetsOf(args).map((to) => ({ kind: 'message' as const, from, to, text }))
  })
}

const DELIVERY_COMMAND = /bot_mode_dm\.py\b[^\n]*--run-delivery/
const DELIVERY_TARGET = /\s-p\s+'?([A-Za-z0-9][\w.-]*)'?\s*$/m
const OUTCOME_HANDLE = /^\s*@?([^\s:@]+?)(?:@\S+)?\s+(?:answered|finished|never)\b/

/** JSON output of the delivery process, even when cut off by the gateway. */
function deliveryOutput(content: string): { fields: Json; raw: string } {
  const body = content.replace(GATEWAY_FOOTER, '').replace(/\s*\]\s*$/, '')
  const at = body.indexOf('\nOutput:')
  const raw = at < 0 ? '' : body.slice(at + '\nOutput:'.length).trim()
  const start = raw.indexOf('{')
  if (start < 0) return { fields: {}, raw }
  try { return { fields: asObject(JSON.parse(raw.slice(start))), raw } } catch { /* truncated output: fields one by one */ }
  const field = (key: string) => {
    const match = new RegExp(`"${key}"\\s*:\\s*"((?:[^"\\\\]|\\\\.)*)`).exec(raw)
    if (!match) return undefined
    try { return JSON.parse(`"${match[1]}"`) as string } catch { return match[1].replace(/\\$/, '') }
  }
  return { fields: { outcome: field('outcome'), reply: field('reply') }, raw }
}

/** End of a delivery on the sender `to`’s side: the contacted bot’s reply, or the reason for its silence. */
export function parseAgentReply(content: string, to: string): AgentMessage | null {
  if (!DELIVERY_COMMAND.test(content)) return null
  const { fields, raw } = deliveryOutput(content)
  const outcome = asString(fields.outcome).trim()
  const from = OUTCOME_HANDLE.exec(outcome)?.[1] || DELIVERY_TARGET.exec(content)?.[1] || ''
  if (!from) return null
  const reply = asString(fields.reply).trim()
  if (reply && (!outcome || /\banswered\.?$/.test(outcome))) return { kind: 'reply', from, to, text: reply }
  // Long reply: the gateway keeps only its end, without `outcome` or the start of the JSON.
  if (!outcome) return raw ? { kind: 'reply', from, to, text: raw } : null
  return { kind: 'no-reply', from, to, text: outcome }
}

/** Traces of a history row: message received, call sent or reply returned. `profile`: the chat’s bot. */
export function agentMessagesFromRow(row: Json, profile: string): AgentMessage[] {
  const role = asString(row.role)
  if (role === 'tool') {
    if ((asString(row.name) || asString(row.tool_name)) !== 'message_agent' || !row.args) return []
    return agentMessagesFromToolCalls([{ name: 'message_agent', args: row.args }], profile)
  }
  if (role === 'assistant') return agentMessagesFromToolCalls(row.tool_calls, profile)
  if (role !== 'user') return []
  const content = asString(row.text) || asString(row.content)
  const found = parseIncomingAgentMessage(content, profile) || parseAgentReply(content, profile)
  return found ? [found] : []
}

/** Live event: `message_agent`’s `tool.start` (full arguments), or the start of a turn triggered by a message. */
export function agentMessagesFromEvent(type: string | undefined, payload: Json, profile: string): AgentMessage[] {
  if (type === 'tool.start' && payload.name === 'message_agent') return agentMessagesFromToolCalls([{ name: 'message_agent', args: payload.args }], profile)
  if (type !== 'message.start' || typeof payload.text !== 'string') return []
  const found = parseIncomingAgentMessage(payload.text, profile) || parseAgentReply(payload.text, profile)
  return found ? [found] : []
}

/** Thread rows. `system` and non-technical: visible in the thread, outside the Activity tab. */
export function agentChatMessages(agents: AgentMessage[], id: string, createdAt: string | null): ChatMessage[] {
  return agents.map((agent, index) => ({ id: agents.length > 1 ? `${id}-agent-${index}` : `${id}-agent`, role: 'system', content: agent.text, createdAt, agent }))
}
