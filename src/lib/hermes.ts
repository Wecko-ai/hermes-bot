const asObject = (value: unknown): Json => (value && typeof value === 'object' && !Array.isArray(value) ? value as Json : {})
const SILENT_MESSAGES = new Set(['SILENT', '[SILENT]', 'NOREPLY', '[NOREPLY]', 'NO_REPLY', '[NO_REPLY]', 'NO RESPONSE', '[NO RESPONSE]'])
export const isSilentMessage = (content: string) => SILENT_MESSAGES.has(content.trim().toUpperCase())
/** Pendant le streaming : vrai tant que le texte peut encore devenir `NOREPLY`, `[SILENT]`… */
export const mayBecomeSilent = (content: string) => {
  const text = content.trim().toUpperCase()
  return [...SILENT_MESSAGES].some((silent) => silent.startsWith(text))
}

// Ce que la gateway dépose au nom de l’utilisateur : fin de processus, compte rendu de routine,
// résumé de compaction, message d’un autre bot. Ces messages vont dans Activité, jamais dans le fil ni le roster.
// Les lignes anciennes n’ont pas de `display_kind` : le début du texte les reconnaît.
const GATEWAY_DISPLAY_KINDS = new Set(['hidden', 'internal_notification', 'process_complete', 'async_delegation_complete', 'model_switch', 'auto_continue', 'personality_switch'])
const GATEWAY_FOOTER = '[INTERNAL NOTIFICATION — generated by the Hermes gateway'
const GATEWAY_MESSAGE = /^\s*(?:\[IMPORTANT: (?:Background process|\d+ background process|You are running as a scheduled cron job|MCP servers have been reloaded)|\[ASYNC (?:DELEGATION|BATCH|COMPLETE)|\[Background process \S+ heartbeat|\[CONTEXT (?:COMPACTION|SUMMARY)|\[(?:END OF )?PRIOR CONTEXT|\[Cronjob "|Cronjob Response:|\[System(?: note)?:|\[Runtime note:|\[Your active task list|\[Planning state preserved|\[OUT-OF-BAND USER MESSAGE|Message from (?:🤖|agent ')|A background (?:fan-out of \d+ subagent\(s\) you|subagent you) dispatched earlier has finished\.)/
// Un message envoyé pendant un tour revient de la gateway dans cette enveloppe : seul le texte est de l’utilisateur.
const STEER_WRAPPER = /^\[OUT-OF-BAND USER MESSAGE[^\]]*\]\s*([\s\S]*?)\s*\[\/OUT-OF-BAND USER MESSAGE\]$/
export const isGatewayMessage = (content: string, displayKind = '') =>
  content.includes(GATEWAY_FOOTER)
  || GATEWAY_MESSAGE.test(content)
  || GATEWAY_DISPLAY_KINDS.has(displayKind)

const asString = (value: unknown, fallback = '') => typeof value === 'string' ? value : fallback
const asNumber = (value: unknown, fallback = 0) => typeof value === 'number' && Number.isFinite(value) ? value : fallback
const isoDate = (value: unknown): string | null => {
  const numeric = asNumber(value)
  if (!numeric) return typeof value === 'string' && value ? value : null
  return new Date(numeric < 1_000_000_000_000 ? numeric * 1000 : numeric).toISOString()
}

/** Ce que l’utilisateur a écrit, sans la note de mentions ni les références `@file:` ajoutées pour le bot. */
const cleanUserText = (text: string) => withoutFileRefs(withoutMentionNote(text))

function textContent(message: Json): string {
  for (const candidate of [message.text, message.content, message.display_text]) {
    if (typeof candidate === 'string') return candidate
    if (Array.isArray(candidate)) {
      return candidate.map((part) => {
        if (typeof part === 'string') return part
        const item = asObject(part)
        if (typeof item.text === 'string') return item.text
        if (typeof item.content === 'string') return item.content
        if (item.type === 'image' || item.type === 'image_url') return '[Image]'
        return ''
      }).filter(Boolean).join('\n')
    }
  }
  return ''
}

/** Une ligne d’historique. `profile` : le bot du chat, envoyeur ou destinataire d’un message entre bots. */
function mapMessages(value: unknown, index: number, profile: string): ChatMessage[] {
  const wrapper = asObject(value)
  const message = Object.keys(asObject(wrapper.message)).length ? { ...wrapper, ...asObject(wrapper.message) } : wrapper
  const id = asString(message.id) || String(message.row_id ?? `message-${index}`)
  const createdAt = isoDate(message.timestamp ?? message.created_at)
  const agents = agentChatMessages(agentMessagesFromRow(message, profile), asString(message.tool_call_id) || id, createdAt)
  const rawRole = asString(message.role, 'system')
  // Message reçu ou réponse renvoyée : la ligne « Orion messaged Iris » remplace le texte de la gateway.
  if (agents.length && (rawRole === 'user' || rawRole === 'tool')) return agents
  const text = textContent(message).trim()
  if (!text) return agents
  const role = ['user', 'assistant', 'system', 'tool'].includes(rawRole) ? rawRole as ChatMessage['role'] : 'system'
  const content = role === 'user' ? cleanUserText(text.replace(STEER_WRAPPER, '$1')) : text
  const silent = isSilentMessage(content)
  const fromGateway = role === 'user' && isGatewayMessage(content, asString(message.display_kind))
  // Historique brut : le texte de l’assistant, puis ses appels `message_agent`.
  return [{
    id,
    role,
    content,
    createdAt,
    technical: silent || fromGateway || role === 'system' || role === 'tool',
  }, ...agents]
}

