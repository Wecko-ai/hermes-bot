/** Plan models served by the provider but missing from the gateway’s catalog. */
const PLAN_MODELS: Record<string, string[]> = { 'kimi-coding': ['k3.1-pro'], anthropic: ['claude-fable-5-2'] }

/** Shown even when the gateway omits the Splash provider (launch config without profile scope, or the Pro has no local :8099). */
export const DEFAULT_SPLASH_MODELS = ['Inkling-2-Mini-128K', 'Inkling-2-Mini-256K']

const LOCAL_PROVIDER_SLUGS = new Set([
  'omlx', 'custom:omlx', 'splash', 'custom:splash',
  'splash-uncensored', 'custom:splash-uncensored',
])

function isLocalProviderSlug(slug: string) {
  return LOCAL_PROVIDER_SLUGS.has(slug) || /(?:^|:)(?:omlx|splash)(?:-|$)/i.test(slug)
}

function extraLocalModels(slug: string, omlxModels: string[], splashModels: string[]) {
  if (slug === 'omlx' || slug === 'custom:omlx') return omlxModels
  if (slug === 'splash' || slug === 'custom:splash') return splashModels
  return []
}

/** `cursor/…` belongs to Cursor, `hermesbot:…` to HermesBot — never keep them under another provider's memory. */
export function rememberedModelBelongsToProvider(slug: string, model: string) {
  const owner = slug.toLowerCase().replace(/^custom:/, '')
  const name = model.toLowerCase()
  if (name.startsWith('cursor/') && owner !== 'cursor') return false
  if (name.startsWith('hermesbot:') && owner !== 'hermesbot') return false
  return true
}

async function loadLocalEndpointModels(endpoint: string): Promise<string[]> {
  try {
    const response = await fetch(endpoint, { credentials: 'same-origin' })
    if (!response.ok) return []
    const body = asObject(await response.json())
    return Array.isArray(body.models) ? body.models.filter((model): model is string => typeof model === 'string' && model !== '') : []
  } catch {
    return []
  }
}

function pushProviderModels(
  options: ModelOption[],
  slug: string,
  providerName: string,
  models: string[],
  pricing: Record<string, unknown>,
  planModels: string[] = [],
  unavailable: Set<string> = new Set(),
) {
  for (const model of planModels) {
    if (!models.includes(model) && !unavailable.has(model)) options.push({ model, provider: slug, providerName, tag: i18n.t('hermes.planTag') })
  }
  for (const model of models) {
    const price = asObject(pricing[model])
    options.push({
      model,
      provider: slug,
      providerName,
      inputPrice: asString(price.input) || undefined,
      outputPrice: asString(price.output) || undefined,
      free: price.free === true || undefined,
    })
  }
}

export async function loadModelOptions(client: HermesClient, profile: string, sessionId?: string): Promise<{ options: ModelOption[]; current: string }> {
  const [result, omlxModels, splashModels] = await Promise.all([
    client.request('model.options', { profile, ...(sessionId ? { session_id: sessionId } : {}) }),
    loadLocalEndpointModels('/api/omlx/models'),
    loadLocalEndpointModels('/api/splash/models'),
  ])
  const options: ModelOption[] = []
  const hiddenProviders = new Set(getAppConfig().ui.hiddenProviders)
  const seenLocal = new Set<string>()
  // A model listed lately stays offered when the gateway answers with its built-in list (see model-memory.ts).
  const memory = readModelMemory()
  const now = Date.now()
  for (const value of Array.isArray(result?.providers) ? result.providers : []) {
    const provider = asObject(value)
    const slug = asString(provider.slug)
    const local = isLocalProviderSlug(slug)
    // Local servers often have no API key: drop only remote providers the gateway marks unauthenticated.
    if (provider.authenticated === false && !local) continue
    if (hiddenProviders.has(slug)) continue
    if (local) seenLocal.add(slug.replace(/^custom:/, ''))
    const unavailable = new Set<string>((Array.isArray(provider.unavailable_models) ? provider.unavailable_models : []).filter((model: unknown): model is string => typeof model === 'string'))
    const pricing = asObject(provider.pricing)
    const listed = (Array.isArray(provider.models) ? provider.models : []).filter((model: unknown): model is string => typeof model === 'string' && !unavailable.has(model))
    for (const model of extraLocalModels(slug, omlxModels, splashModels)) {
      if (!unavailable.has(model) && !listed.includes(model)) listed.push(model)
    }
    let models: string[]
    if (local) {
      // Local servers report their live /v1/models list; never revive retired local ids from 7-day OAuth memory.
      models = listed.filter((model) => rememberedModelBelongsToProvider(slug, model))
      delete memory[slug]
    } else {
      const kept = withRememberedModels(listed, memory[slug], now, unavailable)
      models = kept.models.filter((model) => rememberedModelBelongsToProvider(slug, model))
      memory[slug] = kept.memory.filter(([model]) => rememberedModelBelongsToProvider(slug, model))
    }
    const name = asString(provider.name, slug)
    pushProviderModels(options, slug, name, models, pricing, PLAN_MODELS[slug] ?? [], unavailable)
  }
  // If the gateway catalog was built without a profile (no Splash in the launch config) or
  // /api/splash/models could not reach this Mac, still offer the Inkling aliases the bots use.
  if (!seenLocal.has('splash') && !hiddenProviders.has('splash') && !hiddenProviders.has('custom:splash')) {
    const models = splashModels.length ? splashModels : DEFAULT_SPLASH_MODELS
    pushProviderModels(options, 'splash', 'Inkling 2 Mini (Splash)', models, {})
  }
  if (!seenLocal.has('omlx') && omlxModels.length && !hiddenProviders.has('omlx') && !hiddenProviders.has('custom:omlx')) {
    pushProviderModels(options, 'omlx', 'oMLX (local)', omlxModels, {})
  }
  writeModelMemory(memory)
  return { options, current: asString(result?.model) }
}

/** Revision-bounded mutation: the choice stays on this Bot Chat, the Hermes profile is never rewritten. */
export async function switchModel(client: HermesClient, chat: ActiveChat, option: ModelOverride, confirmation?: string) {
  let revision = chat.revision
  let generation = chat.executionGeneration

  for (let attempt = 0; attempt < 2; attempt += 1) {
    try {
      const result = await client.request('session.mutate', {
        profile: chat.profile,
        session_id: chat.sessionId,
        request_id: crypto.randomUUID(),
        expected_revision: revision,
        expected_generation: generation,
        operation: 'model',
        payload: {
          model: option.model,
          provider: option.provider,
          ...(confirmation ? { confirm: confirmation } : {}),
        },
      })
      return {
        ...result,
        ...(result?.status === 'confirmation_required' ? { confirm_required: true } : {}),
        ...(result?.status === 'deferred' ? { deferred: true } : {}),
      }
    } catch (error) {
      const data = asObject((error as { data?: unknown })?.data)
      const reason = asString(data.reason) || (error instanceof Error ? error.message : '')
      const retryable = reason === 'revision_conflict' || reason === 'stale_generation'
      if (attempt > 0 || !retryable || typeof data.revision !== 'number') throw error
      revision = data.revision
      generation = asNumber(data.execution_generation, generation)
    }
  }

  throw new Error(i18n.t('hermes.modelRefused'))
}

/**
 * Free readiness check of one provider for this bot (`setup.runtime_check`): the gateway reads the
 * profile's config and `.env`, no model is called. A route without a usable key otherwise only fails
 * when the next turn builds its agent, and Hermes then falls into its fallback chain. Returns the
 * gateway's reason, or `null` when the route is fine or the answer is unknown (older gateway, probe
 * still running, timeout): an unknown answer never blocks a switch.
 */
export async function checkModelRoute(client: HermesClient, profile: string, provider: string): Promise<{ error: string } | null> {
  if (!provider) return null
  try {
    const result = asObject(await client.request('setup.runtime_check', { profile, provider }, 8_000))
    return result.ok === false ? { error: asString(result.error) || i18n.t('hermes.routeUnusable') } : null
  } catch {
    return null
  }
}

/** One check per distinct provider, in parallel. Only the providers that cannot serve the bot are returned, with their reason. */
export async function checkModelRoutes(client: HermesClient, profile: string, providers: string[]): Promise<Record<string, string>> {
  const unique = [...new Set(providers.filter(Boolean))]
  const answers = await Promise.all(unique.map(async (provider) => [provider, await checkModelRoute(client, profile, provider)] as const))
  return Object.fromEntries(answers.flatMap(([provider, issue]) => issue ? [[provider, issue.error]] : []))
}

const firstNumber = (...values: unknown[]) => values.find((value): value is number => typeof value === 'number' && Number.isFinite(value))

/** Accepts both Hermes views: `Usage` (status bar) and the `session.stats` counters. */
export function parseUsage(value: unknown): Partial<SessionUsage> | null {
  const usage = asObject(value)
  if (Object.keys(usage).length === 0) return null
  const row: Partial<SessionUsage> = {}
  const contextUsed = firstNumber(usage.context_used, usage.context_tokens, usage.last_prompt_tokens)
  if (contextUsed !== undefined) row.contextUsed = contextUsed
  const contextMax = firstNumber(usage.context_max, usage.context_length)
  if (contextMax !== undefined) {
    row.contextMax = contextMax
    const pct = firstNumber(usage.context_percent)
    row.contextPercent = pct ?? (contextMax > 0 && contextUsed !== undefined ? Math.min(100, (contextUsed / contextMax) * 100) : 0)
  } else {
    const pct = firstNumber(usage.context_percent)
    if (pct !== undefined) row.contextPercent = pct
  }
  const averageTps = firstNumber(usage.avg_tps, usage.tokens_per_s)
  if (averageTps !== undefined) row.averageTps = averageTps
  const inputTokens = firstNumber(usage.input, usage.input_tokens, usage.prompt_tokens)
  if (inputTokens !== undefined) row.inputTokens = inputTokens
  const outputTokens = firstNumber(usage.output, usage.output_tokens, usage.completion_tokens)
  if (outputTokens !== undefined) row.outputTokens = outputTokens
  const totalTokens = firstNumber(usage.total, usage.total_tokens)
  if (totalTokens !== undefined) row.totalTokens = totalTokens
  const reasoningTokens = firstNumber(usage.reasoning, usage.reasoning_tokens)
  if (reasoningTokens !== undefined) row.reasoningTokens = reasoningTokens
  const cacheReadTokens = firstNumber(usage.cache_read, usage.cache_read_tokens)
  if (cacheReadTokens !== undefined) row.cacheReadTokens = cacheReadTokens
  const cacheWriteTokens = firstNumber(usage.cache_write, usage.cache_write_tokens)
  if (cacheWriteTokens !== undefined) row.cacheWriteTokens = cacheWriteTokens
  const apiCalls = firstNumber(usage.calls, usage.api_calls)
  if (apiCalls !== undefined) row.apiCalls = apiCalls
  const compressions = firstNumber(usage.compressions, usage.compression_count)
  if (compressions !== undefined) row.compressions = compressions
  const cacheHitPercent = firstNumber(usage.cache_hit_pct)
  if (cacheHitPercent !== undefined) row.cacheHitPercent = cacheHitPercent
  const averageLatency = firstNumber(usage.avg_latency_s)
  if (averageLatency !== undefined) row.averageLatency = averageLatency
  const activeSubagents = firstNumber(usage.active_subagents)
  if (activeSubagents !== undefined) row.activeSubagents = activeSubagents
  const lastTurnTokens = firstNumber(usage.last_turn_tokens)
  if (lastTurnTokens !== undefined) row.lastTurnTokens = lastTurnTokens
  const costUsd = firstNumber(usage.cost_usd)
  if (costUsd !== undefined) row.costUsd = costUsd
  const source = asString(usage.context_source)
  if (typeof usage.context_estimated === 'boolean') row.contextEstimated = usage.context_estimated
  else if (source) row.contextEstimated = source !== 'provider_usage'
  const model = asString(usage.model)
  if (model) row.model = model
  const provider = asString(usage.provider)
  if (provider && !isStaleOmlxProvider(provider, model)) row.provider = provider
  const plan = asObject(usage.plan_gauge)
  if (typeof plan.used_bp === 'number') {
    row.plan = { label: asString(plan.label, i18n.t('hermes.planDefault')), usedPercent: plan.used_bp / 100, resetsAt: firstNumber(plan.resets_at_ms) ?? null }
  }
  return Object.keys(row).length ? row : null
}

/** Fills missing session counters when a partial frame is the only read available. */
export function completeUsage(partial: Partial<SessionUsage>): SessionUsage {
  return {
    contextUsed: partial.contextUsed ?? 0,
    contextMax: partial.contextMax ?? 0,
    contextPercent: partial.contextPercent ?? 0,
    averageTps: partial.averageTps ?? 0,
    inputTokens: partial.inputTokens ?? 0,
    outputTokens: partial.outputTokens ?? 0,
    totalTokens: partial.totalTokens ?? 0,
    reasoningTokens: partial.reasoningTokens,
    cacheReadTokens: partial.cacheReadTokens,
    cacheWriteTokens: partial.cacheWriteTokens,
    apiCalls: partial.apiCalls,
    compressions: partial.compressions,
    cacheHitPercent: partial.cacheHitPercent,
    averageLatency: partial.averageLatency,
    activeSubagents: partial.activeSubagents,
    lastTurnTokens: partial.lastTurnTokens,
    costUsd: partial.costUsd,
    contextEstimated: partial.contextEstimated,
    model: partial.model,
    provider: partial.provider,
    plan: partial.plan,
  }
}

/** A partial frame completes the previous one: the cache read does not fall back to empty at the end of a turn. */
export function mergeUsage(current: SessionUsage | null, next: Partial<SessionUsage> | null) {
  if (!next || Object.keys(next).length === 0) return current
  if (!current) return completeUsage(next)
  const defined = Object.fromEntries(Object.entries(next).filter(([, value]) => value !== undefined))
  return { ...current, ...defined } as SessionUsage
}

/** `session.stats` is the current gateway’s read; `session.usage` only exists on older ones. */
export async function loadUsage(client: HermesClient, chat: ActiveChat) {
  const params = { profile: chat.profile, session_id: chat.sessionId }
  try {
    const parsed = parseUsage(await client.request('session.stats', params))
    return parsed ? completeUsage(parsed) : null
  } catch {
    const parsed = parseUsage(await client.request('session.usage', params))
    return parsed ? completeUsage(parsed) : null
  }
}

export async function loadContextBreakdown(client: HermesClient, chat: ActiveChat): Promise<ContextBreakdown> {
  const result = asObject(await client.request('session.context_breakdown', { profile: chat.profile, session_id: chat.sessionId }))
  const list = (value: unknown) => (Array.isArray(value) ? value.map(asObject) : [])
  return {
    used: asNumber(result.context_used),
    max: asNumber(result.context_max),
    estimated: result.context_estimated === true,
    categories: list(result.categories).map((item) => ({ id: asString(item.id), label: asString(item.label), tokens: asNumber(item.tokens) })).filter((item) => item.tokens > 0),
    files: list(result.context_files).map((item) => ({ label: asString(item.label), tokens: asNumber(item.est_tokens), loaded: item.loaded === true })),
  }
}

/** The whole profile over the period: Bot Chat, background tasks and routines. Read without any model call. */
export async function loadUsageHistory(profile: string, days = 30): Promise<UsageHistory> {
  const result = asObject(await fetchJson(`/api/hermes/analytics/usage?${new URLSearchParams({ days: String(days), profile })}`))
  const totals = asObject(result.totals)
  const cost = (row: Json, estimated = 'estimated_cost', actual = 'actual_cost') => asNumber(row[actual]) || asNumber(row[estimated])
  const list = (value: unknown) => (Array.isArray(value) ? value.map(asObject) : [])
  const tokens = (row: Json) => asNumber(row.input_tokens) + asNumber(row.output_tokens)
  return {
    days,
    inputTokens: asNumber(totals.total_input),
    outputTokens: asNumber(totals.total_output),
    cacheReadTokens: asNumber(totals.total_cache_read),
    reasoningTokens: asNumber(totals.total_reasoning),
    costUsd: cost(totals, 'total_estimated_cost', 'total_actual_cost'),
    sessions: asNumber(totals.total_sessions),
    apiCalls: asNumber(totals.total_api_calls),
    daily: list(result.daily).map((row) => ({ day: asString(row.day), tokens: tokens(row), costUsd: cost(row) })),
    models: list(result.by_model).map((row) => ({ model: asString(row.model, i18n.t('hermes.unknownModel')), tokens: tokens(row), costUsd: cost(row) })).filter((row) => row.tokens > 0),
  }
}

export async function loadRoutines(profile: string): Promise<Routine[]> {
  const result = await fetchJson<{ jobs?: Json[] } | Json[]>(`/api/hermes/cron/jobs?profile=${encodeURIComponent(profile)}`)
  const jobs = Array.isArray(result) ? result : result.jobs || []
  return jobs.map((job) => {
    const schedule = asObject(job.schedule)
    return {
      id: asString(job.id),
      name: asString(job.name, i18n.t('hermes.routineDefault')),
      prompt: asString(job.prompt) || asString(job.prompt_preview),
      schedule: asString(job.schedule_display || schedule.display || schedule.expr),
      scheduleText: asString(job.schedule_display || schedule.display || schedule.expr, i18n.t('hermes.scheduled')),
      enabled: job.enabled === true,
      nextRunAt: isoDate(job.next_run_at),
      lastRunAt: isoDate(job.last_run_at),
      lastStatus: typeof job.last_status === 'string' ? job.last_status : null,
    }
  })
}
