/** Profils techniques sans conversation (envoi de notifications seul) : jamais montrés, même sans fiche. */
const SYSTEM_PROFILES = new Set(['notify'])

function isRosterProfile(profile: Json): boolean {
  const slug = asString(profile.name)
  return Boolean(slug) && !profile.is_default && !SYSTEM_PROFILES.has(slug)
}

export async function loadRoster(client: HermesClient, browserOwner: () => Promise<string> = loadBrowserOwner): Promise<RosterResponse> {
  const [result, chromeOwner] = await Promise.all([client.request('profiles.list', { include_sessions: true }), browserOwner()])
  const profiles = Array.isArray(result?.profiles) ? result.profiles : []
  // Un profil sans fiche `hermes-bots` (bot créé hors de l’app, sans section) reste visible, dans « Non classés ».
  // Seuls `default` et les profils techniques sans chat (SYSTEM_PROFILES) restent hors du roster.
  const botProfiles = profiles.map(asObject).filter((profile: Json) => isRosterProfile(profile))
  const live = (await loadLiveStatuses(client, botProfiles.map((profile: Json) => asString(profile.name)))).statuses
  const bots = profiles.flatMap((value: unknown, index: number) => {
    const profile = asObject(value)
    const slug = asString(profile.name)
    const metadata = asObject(asObject(profile.ui_meta)['hermes-bots'])
    if (!isRosterProfile(profile)) return []
    const canonical = asObject(profile.canonical_session)
    const worker = asObject(profile.worker_session)
    const workerActive = asNumber(worker.last_active) * 1000 > Date.now() - WORKER_ACTIVE_MS
    const liveStatus = liveTurnStatus(live.get(asString(canonical.resolved_id)) ?? live.get(asString(canonical.id)))
    const turnRunning = canonical.running === true || liveStatus === 'working'
    const browserWorking = chromeOwner === slug
    const status: BotStatus = browserWorking || turnRunning || workerActive ? 'working' : liveStatus
    return [{
      slug,
      sessionId: asString(canonical.resolved_id || canonical.id) || undefined,
      provider: asString(profile.provider) || undefined,
      name: asString(metadata.title || profile.display_name, slug),
      role: asString(metadata.description || profile.description, 'Bot Hermes'),
      section: asString(metadata.sectionName, 'Non classés'),
      sectionId: asString(metadata.sectionId, 'unassigned'),
      model: asString(profile.model, 'Hermes'),
      status,
      workerActive,
      browserOwner: browserWorking || undefined,
      workTitle: browserWorking ? 'Pilote le Chrome partagé' : workerActive ? asString(worker.title) || undefined : undefined,
      preview: (() => {
        const preview = asString(canonical.preview, 'Aucun message pour le moment')
        return isSilentMessage(preview) || isGatewayMessage(preview) ? '' : cleanUserText(preview)
      })(),
      timestamp: isoDate(canonical.last_active ?? canonical.started_at),
      // Le Bot Chat ne bouge pas pendant une tâche de fond : worker_session et last_session complètent.
      lastActivity: Math.max(0, ...[canonical.last_active ?? canonical.started_at, asObject(profile.last_session).last_active, worker.last_active]
        .map((value) => Date.parse(isoDate(value) ?? '') || 0)),
      unread: 0,
      hidden: metadata.hidden === true,
      avatar: {
        shape: asString(metadata.shape, undefined),
        color: asString(metadata.color, undefined),
      },
      _index: index,
    } satisfies Bot & { _index: number }]
  }).sort((a: Bot & { _index: number }, b: Bot & { _index: number }) => {
    const timeA = a.timestamp ? Date.parse(a.timestamp) : 0
    const timeB = b.timestamp ? Date.parse(b.timestamp) : 0
    return timeB - timeA || a._index - b._index
  }).map(({ _index, ...bot }: Bot & { _index: number }) => bot)
  return { bots, health: { connected: true, label: 'Hermes connecté' } }
}

export async function openChat(client: HermesClient, profile: string, sessionIdHint?: string): Promise<{ chat: ActiveChat; messages: ChatMessage[]; prompts: PendingPrompt[] }> {
  let sessionId = sessionIdHint || ''
  if (!sessionId) {
    const roster = await client.request('profiles.list', { include_sessions: true })
    const item = (roster?.profiles || []).find((value: unknown) => asObject(value).name === profile)
    const canonical = asObject(asObject(item).canonical_session)
    sessionId = asString(canonical.resolved_id || canonical.id)
  }

  if (!sessionId) {
    const listed = await client.request('session.list', { profile, title: 'Bot Chat', include_hidden: true, limit: 200 })
    const found = (listed?.sessions || []).find((value: unknown) => asObject(value).root_title === 'Bot Chat' || asObject(value).title === 'Bot Chat')
    const foundSession = asObject(found)
    sessionId = asString(foundSession.resolved_id || foundSession.session_id || foundSession.id)
  }
  if (!sessionId) {
    const created = await client.request('session.create', {
      profile,
      request_id: crypto.randomUUID(),
      source: 'gui',
      title: 'Bot Chat',
      hidden: true,
    })
    sessionId = asString(created?.session_id || created?.stored_session_id)
  }
  if (!sessionId) throw new Error('Le Bot Chat est introuvable.')

  const snapshot = await client.request('session.resume', {
    profile,
    session_id: sessionId,
    source: 'gui',
    omit_messages: false,
    display_projection: true,
  })
  deliverOpenRequests(client, snapshot?.open_requests)
  const rawMessages = snapshot?.display_messages || snapshot?.messages || []
  let messages = (rawMessages as unknown[]).flatMap((value, index) => mapMessages(value, index, profile))
  if (messages.length === 0) {
    const history = await client.request('session.history', { profile, session_id: sessionId })
    messages = ((history?.messages || []) as unknown[]).flatMap((value, index) => mapMessages(value, index, profile))
  }
  return {
    chat: {
      profile,
      sessionId,
      revision: asNumber(snapshot?.revision),
      executionGeneration: asNumber(snapshot?.execution_generation, 1),
      replayEpoch: asString(snapshot?.replay_epoch, undefined),
      subscriptionId: asString(snapshot?.subscription_id, undefined),
      running: snapshot?.running === true,
      model: asString(asObject(snapshot?.info).model) || undefined,
      socketGeneration: client.generation,
    },
    messages,
    prompts: (Array.isArray(snapshot?.prompts) ? snapshot.prompts as unknown[] : [])
      .map((value) => parsePendingPrompt(sessionId, value))
      .filter((prompt): prompt is PendingPrompt => prompt !== null),
  }
}

/** `apiText` : ce que le modèle lit pour ce tour seulement ; l’historique garde `text`. */
export async function submitPrompt(client: HermesClient, chat: ActiveChat, text: string, attachments: { path: string; mime: string }[] = [], options: { queued?: boolean; apiText?: string } = {}) {
  return client.request('prompt.submit', {
    profile: chat.profile,
    session_id: chat.sessionId,
    submission_id: crypto.randomUUID(),
    text,
    queued: options.queued ?? false,
    ...(options.apiText ? { api_text: options.apiText } : {}),
    ...(attachments.length ? { attachments } : {}),
  })
}

/** Un fichier lourd traverse le tunnel SSH en une seule trame : le délai habituel ne suffit pas. */
const ATTACH_TIMEOUT_MS = 10 * 60_000

export async function attachImageBytes(client: HermesClient, chat: ActiveChat, name: string, dataUrl: string) {
  const [header, data] = dataUrl.split(',')
  const mime = header.match(/data:([^;]+)/)?.[1] || 'image/png'
  const result = await client.request('image.attach_bytes', { profile: chat.profile, session_id: chat.sessionId, content_base64: data, filename: name }, ATTACH_TIMEOUT_MS)
  return { path: asString(result?.path), mime: asString(result?.mime, mime) }
}

