/** Tout le profil sur la période : Bot Chat, tâches de fond et routines. Lecture sans appel de modèle. */
export async function loadUsageHistory(profile: string, days = 30): Promise<UsageHistory> {
  const result = asObject(await fetchJson(`/api/hermes/analytics/usage?${new URLSearchParams({ days: String(days), profile })}`))
  const totals = asObject(result.totals)
  const cost = (row: Json, estimated = 'estimated_cost', actual = 'actual_cost') => asNumber(row[actual]) || asNumber(row[estimated])
  const list = (value: unknown) => (Array.isArray(value) ? value.map(asObject) : [])
  const tokens = (row: Json) => asNumber(row.input_tokens) + asNumber(row.output_tokens)
  return {
    days,
    inputTokens: asNumber(totals.total_input),
    outputTokens: asNumber(totals.total_output),
    cacheReadTokens: asNumber(totals.total_cache_read),
    reasoningTokens: asNumber(totals.total_reasoning),
    costUsd: cost(totals, 'total_estimated_cost', 'total_actual_cost'),
    sessions: asNumber(totals.total_sessions),
    apiCalls: asNumber(totals.total_api_calls),
    daily: list(result.daily).map((row) => ({ day: asString(row.day), tokens: tokens(row), costUsd: cost(row) })),
    models: list(result.by_model).map((row) => ({ model: asString(row.model, 'Inconnu'), tokens: tokens(row), costUsd: cost(row) })).filter((row) => row.tokens > 0),
  }
}

