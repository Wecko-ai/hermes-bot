/** Modèles du forfait servis par le fournisseur, mais absents du catalogue de la gateway. */
const PLAN_MODELS: Record<string, string[]> = { 'kimi-coding': ['k3.1-pro'], anthropic: ['claude-fable-5-2'] }

export async function loadModelOptions(client: HermesClient, profile: string, sessionId?: string): Promise<{ options: ModelOption[]; current: string }> {
  const result = await client.request('model.options', { profile, ...(sessionId ? { session_id: sessionId } : {}) })
  const options: ModelOption[] = []
  for (const value of Array.isArray(result?.providers) ? result.providers : []) {
    const provider = asObject(value)
    if (provider.authenticated === false) continue
    const slug = asString(provider.slug)
    const unavailable = new Set(Array.isArray(provider.unavailable_models) ? provider.unavailable_models : [])
    const pricing = asObject(provider.pricing)
    const listed = Array.isArray(provider.models) ? provider.models : []
    for (const model of PLAN_MODELS[slug] ?? []) {
      if (!listed.includes(model) && !unavailable.has(model)) options.push({ model, provider: slug, providerName: asString(provider.name, slug), tag: 'Abo' })
    }
    for (const model of listed) {
      if (typeof model !== 'string' || unavailable.has(model)) continue
      const price = asObject(pricing[model])
      options.push({
        model,
        provider: slug,
        providerName: asString(provider.name, slug),
        inputPrice: asString(price.input) || undefined,
        outputPrice: asString(price.output) || undefined,
      })
    }
  }
  return { options, current: asString(result?.model) }
}

/** Mutation bornée par révision : le choix reste sur ce Bot Chat, le profil Hermes n’est jamais réécrit. */
export async function switchModel(client: HermesClient, chat: ActiveChat, option: ModelOverride, confirmation?: string) {
  let revision = chat.revision
  let generation = chat.executionGeneration

  for (let attempt = 0; attempt < 2; attempt += 1) {
    try {
      const result = await client.request('session.mutate', {
        profile: chat.profile,
        session_id: chat.sessionId,
        request_id: crypto.randomUUID(),
        expected_revision: revision,
        expected_generation: generation,
        operation: 'model',
        payload: {
          model: option.model,
          provider: option.provider,
          ...(confirmation ? { confirm: confirmation } : {}),
        },
      })
      return {
        ...result,
        ...(result?.status === 'confirmation_required' ? { confirm_required: true } : {}),
        ...(result?.status === 'deferred' ? { deferred: true } : {}),
      }
    } catch (error) {
      const data = asObject((error as { data?: unknown })?.data)
      const reason = asString(data.reason) || (error instanceof Error ? error.message : '')
      const retryable = reason === 'revision_conflict' || reason === 'stale_generation'
      if (attempt > 0 || !retryable || typeof data.revision !== 'number') throw error
      revision = data.revision
      generation = asNumber(data.execution_generation, generation)
    }
  }

  throw new Error('Changement de modèle refusé.')
}

const firstNumber = (...values: unknown[]) => values.find((value): value is number => typeof value === 'number' && Number.isFinite(value))

/** Accepte les deux vues Hermes : `Usage` (barre d’état) et les compteurs de `session.stats`. */
export function parseUsage(value: unknown): SessionUsage | null {
  const usage = asObject(value)
  if (Object.keys(usage).length === 0) return null
  const contextUsed = firstNumber(usage.context_used, usage.context_tokens, usage.last_prompt_tokens) ?? 0
  const contextMax = firstNumber(usage.context_max, usage.context_length) ?? 0
  const plan = asObject(usage.plan_gauge)
  const source = asString(usage.context_source)
  return {
    contextUsed,
    contextMax,
    contextPercent: firstNumber(usage.context_percent) ?? (contextMax ? Math.min(100, (contextUsed / contextMax) * 100) : 0),
    averageTps: firstNumber(usage.avg_tps, usage.tokens_per_s) ?? 0,
    inputTokens: firstNumber(usage.input, usage.input_tokens, usage.prompt_tokens) ?? 0,
    outputTokens: firstNumber(usage.output, usage.output_tokens, usage.completion_tokens) ?? 0,
    totalTokens: firstNumber(usage.total, usage.total_tokens) ?? 0,
    reasoningTokens: firstNumber(usage.reasoning, usage.reasoning_tokens),
    cacheReadTokens: firstNumber(usage.cache_read, usage.cache_read_tokens),
    cacheWriteTokens: firstNumber(usage.cache_write, usage.cache_write_tokens),
    apiCalls: firstNumber(usage.calls, usage.api_calls),
    compressions: firstNumber(usage.compressions, usage.compression_count),
    cacheHitPercent: firstNumber(usage.cache_hit_pct),
    averageLatency: firstNumber(usage.avg_latency_s),
    activeSubagents: firstNumber(usage.active_subagents),
    lastTurnTokens: firstNumber(usage.last_turn_tokens),
    costUsd: firstNumber(usage.cost_usd),
    contextEstimated: typeof usage.context_estimated === 'boolean' ? usage.context_estimated : source ? source !== 'provider_usage' : undefined,
    model: asString(usage.model) || undefined,
    provider: asString(usage.provider) || undefined,
    plan: typeof plan.used_bp === 'number' ? { label: asString(plan.label, 'Forfait'), usedPercent: plan.used_bp / 100, resetsAt: firstNumber(plan.resets_at_ms) ?? null } : undefined,
  }
}

/** Une trame partielle complète la précédente : le cache lu ne retombe pas à vide en fin de tour. */
export function mergeUsage(current: SessionUsage | null, next: SessionUsage | null) {
  if (!next || !current) return next ?? current
  const defined = Object.fromEntries(Object.entries(next).filter(([, value]) => value !== undefined))
  return { ...current, ...defined } as SessionUsage
}

/** `session.stats` est la lecture de la gateway actuelle ; `session.usage` n’existe que sur les anciennes. */
export async function loadUsage(client: HermesClient, chat: ActiveChat) {
  const params = { profile: chat.profile, session_id: chat.sessionId }
  try {
    return parseUsage(await client.request('session.stats', params))
  } catch {
    return parseUsage(await client.request('session.usage', params))
  }
}

