export class HermesRpcError extends Error {
  /** `code`: the JSON-RPC error code; `-32601` says the gateway does not know the method. */
  constructor(message: string, public data: Json = {}, public code?: number) {
    super(message)
    this.name = 'HermesRpcError'
  }
}

const asObject = (value: unknown): Json => (value && typeof value === 'object' && !Array.isArray(value) ? value as Json : {})
const SILENT_MESSAGES = new Set(['SILENT', '[SILENT]', 'NOREPLY', '[NOREPLY]', 'NO_REPLY', '[NO_REPLY]', 'NO RESPONSE', '[NO RESPONSE]'])
export const isSilentMessage = (content: string) => SILENT_MESSAGES.has(content.trim().toUpperCase())
/** While streaming: true as long as the text can still turn into `NOREPLY`, `[SILENT]`… */
export const mayBecomeSilent = (content: string) => {
  const text = content.trim().toUpperCase()
  return [...SILENT_MESSAGES].some((silent) => silent.startsWith(text))
}

// What the gateway deposits on the user’s behalf: process end, routine report,
// compaction summary, message from another bot. These messages go to Activity, never to the thread or the roster.
// Older rows have no `display_kind`: the start of the text identifies them.
const GATEWAY_DISPLAY_KINDS = new Set(['hidden', 'internal_notification', 'process_complete', 'async_delegation_complete', 'model_switch', 'auto_continue', 'personality_switch'])
const GATEWAY_FOOTER = '[INTERNAL NOTIFICATION — generated by the Hermes gateway'
const GATEWAY_MESSAGE = /^\s*(?:\[IMPORTANT: (?:Background process|\d+ background process|You are running as a scheduled cron job|MCP servers have been reloaded)|\[ASYNC (?:DELEGATION|BATCH|COMPLETE)|\[Background process \S+ heartbeat|\[CONTEXT (?:COMPACTION|SUMMARY)|\[(?:END OF )?PRIOR CONTEXT|\[Cronjob "|Cronjob Response:|\[System(?: note)?:|\[Runtime note:|\[Your active task list|\[Planning state preserved|\[OUT-OF-BAND USER MESSAGE|Message from (?:🤖|agent ')|A background (?:fan-out of \d+ subagent\(s\) you|subagent you) dispatched earlier has finished\.)/
// A message sent during a turn comes back from the gateway in this envelope: only the text is the user’s.
const STEER_WRAPPER = /^\[OUT-OF-BAND USER MESSAGE[^\]]*\]\s*([\s\S]*?)\s*\[\/OUT-OF-BAND USER MESSAGE\]$/
export const isGatewayMessage = (content: string, displayKind = '') =>
  content.includes(GATEWAY_FOOTER)
  || GATEWAY_MESSAGE.test(content)
  || GATEWAY_DISPLAY_KINDS.has(displayKind)

const asString = (value: unknown, fallback = '') => typeof value === 'string' ? value : fallback
const asNumber = (value: unknown, fallback = 0) => typeof value === 'number' && Number.isFinite(value) ? value : fallback
const isoDate = (value: unknown): string | null => {
  const numeric = asNumber(value)
  if (!numeric) return typeof value === 'string' && value ? value : null
  return new Date(numeric < 1_000_000_000_000 ? numeric * 1000 : numeric).toISOString()
}

/** What the user wrote, without the mentions note or the `@file:` references added for the bot. */
const cleanUserText = (text: string) => withoutFileRefs(withoutMentionNote(splitUserImages(text).text))

function textContent(message: Json): string {
  for (const candidate of [message.text, message.content, message.display_text]) {
    if (typeof candidate === 'string') return candidate
    if (Array.isArray(candidate)) {
      return candidate.map((part) => {
        if (typeof part === 'string') return part
        const item = asObject(part)
        if (typeof item.text === 'string') return item.text
        if (typeof item.content === 'string') return item.content
        if (item.type === 'image' || item.type === 'image_url') return '[Image]'
        return ''
      }).filter(Boolean).join('\n')
    }
  }
  return ''
}

/** One history row. `profile`: the chat’s bot, sender or recipient of a message between bots. */
function mapMessages(value: unknown, index: number, profile: string): ChatMessage[] {
  const wrapper = asObject(value)
  const message = Object.keys(asObject(wrapper.message)).length ? { ...wrapper, ...asObject(wrapper.message) } : wrapper
  const id = asString(message.id) || String(message.row_id ?? `message-${index}`)
  const createdAt = isoDate(message.timestamp ?? message.created_at)
  const agents = agentChatMessages(agentMessagesFromRow(message, profile), asString(message.tool_call_id) || id, createdAt)
  const rawRole = asString(message.role, 'system')
  // Message received or reply sent back: the “Orion messaged Iris” line replaces the gateway’s text.
  if (agents.length && (rawRole === 'user' || rawRole === 'tool')) return agents
  // `delegate_task` call: its row has no text, but its arguments hold each child's prompt.
  if (rawRole === 'tool' && (asString(message.name) || asString(message.tool_name)) === 'delegate_task') {
    const tasks = delegationTasks(message.args)
    if (!tasks.length) return agents
    const goals = tasks.map((task) => subagentTitle(task.goal, 70)).join(' · ')
    return [{ id, role: 'tool', content: i18n.t('subagents.dispatched', { count: tasks.length, goals }), createdAt, technical: true, delegation: tasks }, ...agents]
  }
  const text = textContent(message).trim()
  if (!text) return agents
  const role = ['user', 'assistant', 'system', 'tool'].includes(rawRole) ? rawRole as ChatMessage['role'] : 'system'
  const sent = role === 'user' ? splitUserImages(text.replace(STEER_WRAPPER, '$1')) : { text, images: [] }
  const content = role === 'user' ? cleanUserText(sent.text) : text
  if (!content && !sent.images.length) return agents
  const silent = isSilentMessage(content)
  const fromGateway = role === 'user' && isGatewayMessage(content, asString(message.display_kind))
  // The first turn of a bot created here: Activity only, never a bubble of the user.
  const kickoff = role === 'user' && isKickoffMessage(content)
  // Raw history: the assistant’s text, then its `message_agent` calls.
  return [{
    id,
    role,
    content,
    createdAt,
    technical: silent || fromGateway || kickoff || role === 'system' || role === 'tool',
    ...(sent.images.length ? { images: sent.images } : {}),
  }, ...agents]
}

/** Same window as `workerActiveAt` in Hermes Desktop’s Bot Mode. */
const WORKER_ACTIVE_MS = 150_000

/** Gateway request waiting for an answer from the user (vault, approval). */
export interface ServerRequest {
  id: string
  method: string
  params: Json
}

const ANSWERED_HERE = new Set(['approval', 'vault.save_login', 'vault.unlock_prompt', 'vault.code'])
/** Reserved for a window that displays the session: the 4404 refusal lets another window answer. */
const WINDOW_OWNED = new Set(['preview.act', 'preview.read', 'terminal.read', 'theme.apply', 'window.read', 'tour'])

export class HermesClient {
  private serverRequestListeners = new Set<(request: ServerRequest) => void>()
  private socket: WebSocket | null = null
  private sequence = 0
  private pending = new Map<string, PendingRequest>()
  private listeners = new Set<(event: RpcEvent) => void>()
  private readyPromise: Promise<void> | null = null
  private connectionListeners = new Set<(connected: boolean) => void>()
  /** Incremented on each new socket: session subscriptions do not survive a reconnection. */
  generation = 0

  async connect() {
    // CONNECTING included: the roster refresh and the reconnect button share the same socket.
    if (this.readyPromise && this.socket && this.socket.readyState <= WebSocket.OPEN) return this.readyPromise
    this.rejectPending()
    this.readyPromise = new Promise<void>((resolve, reject) => {
      const protocol = location.protocol === 'https:' ? 'wss' : 'ws'
      const socket = new WebSocket(`${protocol}://${location.host}/api/ws?profile=default`, 'hermes-gateway-v1')
      this.socket = socket
      this.generation += 1
      const timer = setTimeout(() => {
        reject(new Error(i18n.t('hermes.gatewayUnresponsive')))
        // An open but silent socket would be reused: closing it lets us start over from scratch.
        socket.close()
      }, 20_000)
      socket.onmessage = (message) => {
        if (this.socket !== socket) return
        let frame: Json
        try { frame = JSON.parse(String(message.data)) } catch { return }
        const id = frame.id
        if (typeof frame.method === 'string' && frame.method !== 'event' && typeof id === 'string') {
          this.receiveServerRequest({ id, method: frame.method, params: asObject(frame.params) })
          return
        }
        if (id !== undefined && id !== null) {
          const request = this.pending.get(String(id))
          if (!request) return
          this.pending.delete(String(id))
          clearTimeout(request.timer)
          if (frame.error) {
            const error = asObject(frame.error)
            request.reject(new HermesRpcError(asString(error.message, i18n.t('hermes.requestRefused')), asObject(error.data), typeof error.code === 'number' ? error.code : undefined))
          } else request.resolve(frame.result)
          return
        }
        if (frame.method === 'event') {
          const event = asObject(frame.params) as RpcEvent
          if (event.type === 'gateway.ready') {
            clearTimeout(timer)
            // Without this announcement, the gateway fails vault and approval requests instead of sending them.
            socket.send(JSON.stringify({ jsonrpc: '2.0', id: `hermesbot-${++this.sequence}`, method: 'client.capabilities', params: { server_requests: true } }))
            this.connectionListeners.forEach((listener) => listener(true))
            resolve()
          }
          this.listeners.forEach((listener) => listener(event))
        }
      }
      socket.onerror = () => {
        clearTimeout(timer)
        reject(new Error(i18n.t('hermes.connectFailed')))
      }
      socket.onclose = () => {
        clearTimeout(timer)
        reject(new Error(i18n.t('hermes.connectionClosed')))
        // A socket that has already been replaced no longer touches the new one’s state or requests.
        if (this.socket !== socket) return
        this.socket = null
        this.readyPromise = null
        this.connectionListeners.forEach((listener) => listener(false))
        this.rejectPending()
      }
    })
    return this.readyPromise
  }

  private rejectPending() {
    this.pending.forEach((request) => {
      clearTimeout(request.timer)
      request.reject(new Error(i18n.t('hermes.connectionClosed')))
    })
    this.pending.clear()
  }

  onConnection(listener: (connected: boolean) => void) {
    this.connectionListeners.add(listener)
    return () => this.connectionListeners.delete(listener)
  }

  onServerRequest(listener: (request: ServerRequest) => void) {
    this.serverRequestListeners.add(listener)
    return () => this.serverRequestListeners.delete(listener)
  }

  /** Also receives the still-open requests that a session resume hands back. */
  receiveServerRequest(request: ServerRequest) {
    if (ANSWERED_HERE.has(request.method)) {
      this.serverRequestListeners.forEach((listener) => listener(request))
      return
    }
    // An unanswered request would block the bot until its timeout: refuse it right away.
    this.sendFrame({
      jsonrpc: '2.0',
      id: request.id,
      error: WINDOW_OWNED.has(request.method) ? { code: 4404, message: 'session_not_shown' } : { code: -32601, message: `unsupported: ${request.method}` },
    })
  }

  respond(id: string, result: Json) {
    this.sendFrame({ jsonrpc: '2.0', id, result })
  }

  private sendFrame(frame: Json) {
    if (this.socket?.readyState !== WebSocket.OPEN) throw new Error(i18n.t('hermes.disconnected'))
    this.socket.send(JSON.stringify(frame))
  }

  onEvent(listener: (event: RpcEvent) => void) {
    this.listeners.add(listener)
    return () => this.listeners.delete(listener)
  }

  async request<T = any>(method: string, params: Json = {}, timeoutMs = 45_000): Promise<T> {
    await this.connect()
    const socket = this.socket
    if (!socket || socket.readyState !== WebSocket.OPEN) throw new Error(i18n.t('hermes.disconnected'))
    const id = `hermesbot-${++this.sequence}`
    return new Promise<T>((resolve, reject) => {
      const timer = setTimeout(() => {
        this.pending.delete(id)
        reject(new Error(i18n.t('hermes.noAnswer', { method })))
      }, timeoutMs)
      this.pending.set(id, { resolve, reject, timer })
      socket.send(JSON.stringify({ jsonrpc: '2.0', id, method, params }))
    })
  }

  close() {
    this.socket?.close()
    this.socket = null
    this.readyPromise = null
    this.rejectPending()
  }
}

export async function fetchJson<T>(path: string): Promise<T> {
  const response = await fetch(path, { credentials: 'same-origin', headers: { Accept: 'application/json' } })
  const body = await response.json().catch(() => ({}))
  if (!response.ok) {
    const error = new Error(asString(body.detail || body.error, i18n.t('hermes.httpError', { status: response.status }))) as Error & { status?: number }
    error.status = response.status
    throw error
  }
  return body as T
}

function deliverOpenRequests(client: HermesClient, value: unknown) {
  if (!Array.isArray(value)) return
  for (const item of value) {
    const entry = asObject(item)
    if (typeof entry.id === 'string' && typeof entry.method === 'string') {
      client.receiveServerRequest({ id: entry.id, method: entry.method, params: asObject(entry.params) })
    }
  }
}

/**
 * Question (`clarify`) or approval (`approval`) that the gateway keeps open during a turn. It arrives through
 * the `clarify.request` / `approval.request` event and through the `prompts` of `session.resume`; it is what
 * makes `session.active_list` report `waiting`. A multi-part question arrives part by part.
 */
export interface PendingPrompt {
  sessionId: string
  kind: 'clarify' | 'approval'
  promptId: string
  generation: number
  question: string
  choices: string[]
  multiSelect: boolean
  command: string
  description: string
}

export function parsePendingPrompt(sessionId: string, value: unknown): PendingPrompt | null {
  const row = asObject(value)
  const kind = row.kind === 'clarify' || row.kind === 'approval' ? row.kind : null
  const promptId = asString(row.prompt_id)
  const generation = row.execution_generation
  if (!sessionId || !kind || !promptId || typeof generation !== 'number' || !Number.isInteger(generation)) return null
  return {
    sessionId,
    kind,
    promptId,
    generation,
    question: asString(row.question),
    choices: Array.isArray(row.choices) ? row.choices.filter((choice): choice is string => typeof choice === 'string' && choice.trim() !== '') : [],
    multiSelect: row.multi_select === true,
    command: asString(row.command),
    description: asString(row.description),
  }
}

/**
 * Answers a question or an approval. `clarify.respond` passes the text to the bot as is: the exact label
 * of the choice, a JSON array of labels for a multiple choice, or a free answer.
 */
export async function answerPrompt(client: HermesClient, profile: string, prompt: PendingPrompt, answer: string) {
  const result = await client.request(prompt.kind === 'clarify' ? 'clarify.respond' : 'approval.respond', {
    profile,
    session_id: prompt.sessionId,
    execution_generation: prompt.generation,
    prompt_id: prompt.promptId,
    ...(prompt.kind === 'clarify' ? { answer } : { choice: answer }),
  })
  return asString(asObject(result).status)
}

export interface LiveStatuses {
  /** Status by session id: `working`, `waiting`, `starting` or `idle`. */
  statuses: Map<string, string>
  /** Profiles that answered: for the others, the absence of a session says nothing. */
  answered: Set<string>
}

/**
 * Real state of the turns, profile by profile. `profiles.list` does not say whether a Bot Chat turn is
 * running, and `session.active_list` without `profile` only lists the `default` sessions: a bot woken
 * by another bot stayed “available” until its chat was opened.
 */
export async function loadLiveStatuses(client: HermesClient, profiles: string[]): Promise<LiveStatuses> {
  const statuses = new Map<string, string>()
  const answered = new Set<string>()
  await Promise.all(profiles.map(async (profile) => {
    try {
      const result = await client.request('session.active_list', { profile }, 10_000)
      answered.add(profile)
      const rows: unknown[] = Array.isArray(result?.sessions) ? result.sessions : []
      for (const value of rows) {
        const row = asObject(value)
        for (const id of [asString(row.session_key), asString(row.id)]) if (id) statuses.set(id, asString(row.status))
      }
    } catch {
      // Profile not served, older gateway or outage: only events and workers remain.
    }
  }))
  return { statuses, answered }
}

/** `working` for a running or admitted turn, `waiting` if it awaits an answer, `idle` if there is no turn. */
export function liveTurnStatus(status: string | undefined): 'working' | 'waiting' | 'idle' {
  if (status === 'working' || status === 'starting') return 'working'
  return status === 'waiting' ? 'waiting' : 'idle'
}

/** Side-effect-free re-read of a session’s latest events: useful for a bot not yet opened. */
export async function loadSessionEvents(client: HermesClient, profile: string, sessionId: string, lastSeen: number) {
  const result = await client.request('session.events.since', { profile, session_id: sessionId, last_seen: lastSeen })
  deliverOpenRequests(client, result?.open_requests)
  return { events: (Array.isArray(result?.events) ? result.events : []) as RpcEvent[], latestSeq: asNumber(result?.latest_seq, lastSeen) }
}

/** A bot holding a team's Chrome, and since when (milliseconds) if the arbiter says. */
export interface BrowserTurn {
  owner: string
  since?: number
}

function asBrowserTurn(value: unknown): BrowserTurn | null {
  if (typeof value === 'string') return value ? { owner: value } : null
  const row = asObject(value)
  const owner = asString(row.owner)
  if (!owner) return null
  // ISO from the server, milliseconds once read.
  const since = typeof row.since === 'number' ? row.since : Date.parse(asString(row.since))
  return Number.isFinite(since) ? { owner, since } : { owner }
}

/** Chrome turns (one per team). An older server only returns `owners`, or a single `owner`. */
export async function loadBrowserOwner(): Promise<BrowserTurn[]> {
  try {
    const result = await fetchJson<{ owner?: unknown; owners?: unknown; turns?: unknown }>('/api/browser-turn')
    const rows: unknown[] = Array.isArray(result.turns) ? result.turns : Array.isArray(result.owners) ? result.owners : [result.owner]
    return rows.map(asBrowserTurn).filter((turn): turn is BrowserTurn => turn !== null)
  } catch {
    return []
  }
}

/** Technical profiles without a conversation (notification sending only): never shown, even without a card. */
const SYSTEM_PROFILES = new Set(['notify'])

function isRosterProfile(profile: Json): boolean {
  const slug = asString(profile.name)
  // A bot deleted from this app keeps its profile: only its mark takes it out of the roster.
  return Boolean(slug) && !profile.is_default && !SYSTEM_PROFILES.has(slug) && !isRemovedProfile(profile.ui_meta)
}

export async function loadRoster(client: HermesClient, browserOwner: () => Promise<string | Array<string | BrowserTurn>> = loadBrowserOwner): Promise<RosterResponse> {
  const [result, chromeOwnerValue] = await Promise.all([client.request('profiles.list', { include_sessions: true }), browserOwner()])
  const chromeTurns = (Array.isArray(chromeOwnerValue) ? chromeOwnerValue : [chromeOwnerValue])
    .map(asBrowserTurn).filter((turn): turn is BrowserTurn => turn !== null)
  const profiles = Array.isArray(result?.profiles) ? result.profiles : []
  // A profile without a `hermes-bots` card (bot created outside the app, no section) stays visible, under “Non classés”.
  // Only `default`, the technical profiles without a chat (SYSTEM_PROFILES) and the bots deleted here stay out of the roster.
  const botProfiles = profiles.map(asObject).filter((profile: Json) => isRosterProfile(profile))
  const live = (await loadLiveStatuses(client, botProfiles.map((profile: Json) => asString(profile.name)))).statuses
  const bots = profiles.flatMap((value: unknown, index: number) => {
    const profile = asObject(value)
    const slug = asString(profile.name)
    const metadata = asObject(asObject(profile.ui_meta)['hermes-bots'])
    if (!isRosterProfile(profile)) return []
    const canonical = asObject(profile.canonical_session)
    const worker = asObject(profile.worker_session)
    const workerActive = asNumber(worker.last_active) * 1000 > Date.now() - WORKER_ACTIVE_MS
    const liveStatus = liveTurnStatus(live.get(asString(canonical.resolved_id)) ?? live.get(asString(canonical.id)))
    const turnRunning = canonical.running === true || liveStatus === 'working'
    // Holding a Chrome is not working: a bot whose Bot Chat turn ended after it took the Chrome
    // keeps it while it waits for the user. A turn taken by a worker (cron) still counts.
    const chromeTurn = chromeTurns.find((turn) => turn.owner === slug)
    const chatActive = Date.parse(isoDate(canonical.last_active) ?? '') || 0
    const heldWhileIdle = chromeTurn?.since !== undefined && !turnRunning && liveStatus === 'idle' && chatActive >= chromeTurn.since
    const browserWorking = Boolean(chromeTurn) && !heldWhileIdle
    const status: BotStatus = browserWorking || turnRunning || workerActive ? 'working' : liveStatus
    return [{
      slug,
      sessionId: asString(canonical.resolved_id || canonical.id) || undefined,
      provider: asString(profile.provider) || undefined,
      name: asString(metadata.title || profile.display_name, slug),
      role: asString(metadata.description || profile.description, i18n.t('hermes.defaultRole')),
      section: asString(metadata.sectionName) || UNASSIGNED_SECTION_NAME,
      sectionId: asString(metadata.sectionId) || UNASSIGNED_SECTION_ID,
      model: asString(profile.model, 'Hermes'),
      status,
      workerActive,
      browserOwner: browserWorking || undefined,
      workTitle: browserWorking ? i18n.t('hermes.drivingChrome') : workerActive ? asString(worker.title) || undefined : undefined,
      preview: (() => {
        const preview = asString(canonical.preview, i18n.t('hermes.noMessage'))
        // Hermes previews the first user message: for a bot created here, the kickoff sentence.
        return isSilentMessage(preview) || isGatewayMessage(preview) || isKickoffPreview(preview) ? '' : cleanUserText(preview)
      })(),
      timestamp: isoDate(canonical.last_active ?? canonical.started_at),
      // The Bot Chat does not move during a background task: worker_session and last_session fill in.
      lastActivity: Math.max(0, ...[canonical.last_active ?? canonical.started_at, asObject(profile.last_session).last_active, worker.last_active]
        .map((value) => Date.parse(isoDate(value) ?? '') || 0)),
      unread: 0,
      hidden: metadata.hidden === true,
      avatar: {
        shape: asString(metadata.shape, undefined),
        color: asString(metadata.color, undefined),
      },
      _index: index,
    } satisfies Bot & { _index: number }]
  }).sort((a: Bot & { _index: number }, b: Bot & { _index: number }) => {
    const timeA = a.timestamp ? Date.parse(a.timestamp) : 0
    const timeB = b.timestamp ? Date.parse(b.timestamp) : 0
    return timeB - timeA || a._index - b._index
  }).map(({ _index, ...bot }: Bot & { _index: number }) => bot)
  return { bots, health: { connected: true, label: i18n.t('hermes.connected') } }
}

export async function openChat(client: HermesClient, profile: string, sessionIdHint?: string): Promise<{ chat: ActiveChat; messages: ChatMessage[]; prompts: PendingPrompt[] }> {
  let sessionId = sessionIdHint || ''
  if (!sessionId) {
    const roster = await client.request('profiles.list', { include_sessions: true })
    const item = (roster?.profiles || []).find((value: unknown) => asObject(value).name === profile)
    const canonical = asObject(asObject(item).canonical_session)
    sessionId = asString(canonical.resolved_id || canonical.id)
  }

  if (!sessionId) {
    const listed = await client.request('session.list', { profile, title: 'Bot Chat', include_hidden: true, limit: 200 })
    const found = (listed?.sessions || []).find((value: unknown) => asObject(value).root_title === 'Bot Chat' || asObject(value).title === 'Bot Chat')
    const foundSession = asObject(found)
    sessionId = asString(foundSession.resolved_id || foundSession.session_id || foundSession.id)
  }
  if (!sessionId) {
    const created = await client.request('session.create', {
      profile,
      request_id: crypto.randomUUID(),
      source: 'gui',
      title: 'Bot Chat',
      hidden: true,
    })
    sessionId = asString(created?.session_id || created?.stored_session_id)
  }
  if (!sessionId) throw new Error(i18n.t('hermes.chatNotFound'))

  const snapshot = await client.request('session.resume', {
    profile,
    session_id: sessionId,
    source: 'gui',
    omit_messages: false,
    display_projection: true,
  })
  deliverOpenRequests(client, snapshot?.open_requests)
  const rawMessages = snapshot?.display_messages || snapshot?.messages || []
  let messages = (rawMessages as unknown[]).flatMap((value, index) => mapMessages(value, index, profile))
  if (messages.length === 0) {
    const history = await client.request('session.history', { profile, session_id: sessionId })
    messages = ((history?.messages || []) as unknown[]).flatMap((value, index) => mapMessages(value, index, profile))
  }
  return {
    chat: {
      profile,
      sessionId,
      revision: asNumber(snapshot?.revision),
      executionGeneration: asNumber(snapshot?.execution_generation, 1),
      replayEpoch: asString(snapshot?.replay_epoch, undefined),
      subscriptionId: asString(snapshot?.subscription_id, undefined),
      running: snapshot?.running === true,
      model: asString(asObject(snapshot?.info).model) || undefined,
      socketGeneration: client.generation,
    },
    messages,
    prompts: (Array.isArray(snapshot?.prompts) ? snapshot.prompts as unknown[] : [])
      .map((value) => parsePendingPrompt(sessionId, value))
      .filter((prompt): prompt is PendingPrompt => prompt !== null),
  }
}

