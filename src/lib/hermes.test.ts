describe('statut réel du roster', () => {
  const profile = { name: 'orion', ui_meta: { 'hermes-bots': { title: 'Orion' } }, canonical_session: { id: 'racine', resolved_id: 'chat', last_active: 1_000 } }
  const roster = (status: string | Error) => loadRoster({
    request: vi.fn(async (method: string) => {
      if (method === 'profiles.list') return { profiles: [profile] }
      if (status instanceof Error) throw status
      return { sessions: [{ id: 'vivant', session_key: 'chat', status }] }
    }),
  } as unknown as HermesClient)

  it('voit un tour de Bot Chat en cours et une attente de réponse', async () => {
    expect((await roster('working')).bots[0].status).toBe('working')
    expect((await roster('waiting')).bots[0].status).toBe('waiting')
    expect((await roster('idle')).bots[0].status).toBe('idle')
  })

  it('demande les tours profil par profil : sans profil, la gateway ne liste que default', async () => {
    const iris = { name: 'iris', ui_meta: { 'hermes-bots': { title: 'Iris' } }, canonical_session: { id: 'chat-iris', last_active: 900 } }
    const request = vi.fn(async (method: string, params: { profile?: string }) => {
      if (method === 'profiles.list') return { profiles: [profile, iris, { name: 'default', is_default: true, ui_meta: {} }, { name: 'notify', ui_meta: {} }] }
      if (!params.profile) return { sessions: [] }
      if (params.profile === 'orion') throw new Error('profile_mismatch')
      return { sessions: params.profile === 'iris' ? [{ id: 'chat-iris', session_key: 'chat-iris', status: 'starting' }] : [] }
    })
    const { bots } = await loadRoster({ request } as unknown as HermesClient, async () => '')
    expect(request.mock.calls.filter(([method]) => method === 'session.active_list').map(([, params]) => params)).toEqual([{ profile: 'orion' }, { profile: 'iris' }])
    expect(Object.fromEntries(bots.map((bot) => [bot.slug, bot.status]))).toEqual({ orion: 'idle', iris: 'working' })
  })

  it('montre un bot sans fiche hermes-bots dans « Non classés », jamais default ni un profil technique', async () => {
    const request = vi.fn(async (method: string) => method === 'profiles.list'
      ? { profiles: [{ name: 'default', is_default: true, ui_meta: {} }, { name: 'notify', ui_meta: {} }, { name: 'vega', description: 'Veille', model: 'kimi' }] }
      : { sessions: [] })
    const { bots } = await loadRoster({ request } as unknown as HermesClient, async () => '')
    expect(bots.map((bot) => [bot.slug, bot.name, bot.role, bot.section, bot.sectionId, bot.hidden])).toEqual([
      ['vega', 'vega', 'Veille', 'Non classés', 'unassigned', false],
    ])
  })

  it('reste utilisable avec une gateway sans session.active_list', async () => {
    expect((await roster(new Error('unknown method'))).bots[0].status).toBe('idle')
  })

  it('marque au travail le bot qui détient le Chrome partagé', async () => {
    const request = vi.fn(async (method: string) => method === 'profiles.list'
      ? { profiles: [profile] }
      : { sessions: [{ id: 'vivant', session_key: 'chat', status: 'idle' }] })
    const client = { request } as unknown as HermesClient
    const owner = await loadRoster(client, async () => 'orion')
    expect(owner.bots[0].status).toBe('working')
    expect(owner.bots[0].workTitle).toBe('Pilote le Chrome partagé')
    const other = await loadRoster(client, async () => 'vega')
    expect(other.bots[0].status).toBe('idle')
  })

  it('marque au travail chaque bot qui détient un Chrome d’équipe', async () => {
    const two = [{ ...profile, name: 'orion' }, { ...profile, name: 'iris' }, { ...profile, name: 'nova' }]
    const request = vi.fn(async (method: string) => method === 'profiles.list'
      ? { profiles: two }
      : { sessions: [{ id: 'vivant', session_key: 'chat', status: 'idle' }] })
    const roster = await loadRoster({ request } as unknown as HermesClient, async () => ['orion', 'nova'])
    const bySlug = Object.fromEntries(roster.bots.map((bot) => [bot.slug, bot]))
    expect(bySlug.orion.workTitle).toBe('Pilote le Chrome partagé')
    expect(bySlug.nova.status).toBe('working')
    expect(bySlug.iris.status).toBe('idle')
  })
})

describe('modèles du forfait', () => {
  const request = (models: string[], authenticated = true) => vi.fn().mockResolvedValue({
    providers: [{ slug: 'kimi-coding', name: 'Kimi', authenticated, models }],
  })

  it('ajoute K3.1 Pro en tête du fournisseur connecté', async () => {
    const { options } = await loadModelOptions({ request: request(['kimi-k3']) } as unknown as HermesClient, 'orion')
    expect(options.map((option) => option.model)).toEqual(['k3.1-pro', 'kimi-k3'])
    expect(options[0]).toMatchObject({ provider: 'kimi-coding', tag: 'Abo' })
  })

  it('ne le propose ni en double, ni sans connexion', async () => {
    const listed = await loadModelOptions({ request: request(['k3.1-pro']) } as unknown as HermesClient, 'orion')
    expect(listed.options.map((option) => option.model)).toEqual(['k3.1-pro'])
    const absent = await loadModelOptions({ request: request(['kimi-k3'], false) } as unknown as HermesClient, 'orion')
    expect(absent.options).toEqual([])
  })

  it('propose Fable 5.2 chez Anthropic, sans le désigner comme modèle courant', async () => {
    const anthropic = (models: string[]) => ({ request: vi.fn().mockResolvedValue({ model: 'claude-opus-5-5', providers: [{ slug: 'anthropic', name: 'Anthropic', authenticated: true, models }] }) }) as unknown as HermesClient
    const added = await loadModelOptions(anthropic(['claude-opus-5-5']), 'orion')
    expect(added.options.map((option) => option.model)).toEqual(['claude-fable-5-2', 'claude-opus-5-5'])
    expect(added.current).toBe('claude-opus-5-5')
    const listed = await loadModelOptions(anthropic(['claude-opus-5-5', 'claude-fable-5-2']), 'orion')
    expect(listed.options.filter((option) => option.model === 'claude-fable-5-2')).toHaveLength(1)
  })
})

describe('changement de modèle', () => {
  it('utilise une mutation de session bornée, sans réécrire le profil', async () => {
    const request = vi.fn().mockResolvedValue({ session_id: 'chat-orion', revision: 5, execution_generation: 2 })
    const result = await switchModel({ request } as unknown as HermesClient, chat, option)

    expect(request).toHaveBeenCalledWith('session.mutate', expect.objectContaining({
      profile: 'orion',
      session_id: 'chat-orion',
      expected_revision: 4,
      expected_generation: 2,
      operation: 'model',
      payload: option,
    }))
    expect(result.revision).toBe(5)
  })

  it('réessaie une fois aux clôtures fournies par la gateway', async () => {
    const request = vi.fn()
      .mockRejectedValueOnce(new HermesRpcError('stale_generation', { reason: 'stale_generation', revision: 6, execution_generation: 3 }))
      .mockResolvedValueOnce({ session_id: 'chat-orion', revision: 7, execution_generation: 3 })
    await switchModel({ request } as unknown as HermesClient, chat, option)

    expect(request).toHaveBeenCalledTimes(2)
    expect(request.mock.calls[1][1]).toMatchObject({ expected_revision: 6, expected_generation: 3 })
    expect(request.mock.calls[1][1].request_id).not.toBe(request.mock.calls[0][1].request_id)
  })

  it('renvoie le jeton de confirmation dans la mutation suivante', async () => {
    const request = vi.fn()
      .mockResolvedValueOnce({ status: 'confirmation_required', confirm: 'confirm-test', confirm_message: 'Confirmer ?' })
      .mockResolvedValueOnce({ session_id: 'chat-orion', revision: 5 })
    const client = { request } as unknown as HermesClient
    const first = await switchModel(client, chat, option)
    expect(first.confirm_required).toBe(true)

    await switchModel(client, chat, option, first.confirm)
    expect(request.mock.calls[1][1].payload).toEqual({ ...option, confirm: 'confirm-test' })
  })

  it('ne propose ni les fournisseurs masqués par les réglages, ni ceux qui ne sont pas connectés', async () => {
    const request = vi.fn().mockResolvedValue({
      model: 'claude-opus-5-5',
      providers: [
        { slug: 'masque', name: 'Masqué', authenticated: true, models: ['modele-masque'] },
        { slug: 'absent', name: 'Non connecté', authenticated: false, models: ['autre-modele'] },
        { slug: 'anthropic', name: 'Anthropic', authenticated: true, models: ['claude-opus-5-5'] },
      ],
    })
    setAppConfig(parseAppConfig({ ui: { hiddenProviders: ['masque'] } }))
    try {
      const result = await loadModelOptions({ request } as unknown as HermesClient, 'orion', 'chat-orion')
      expect(result.options.map((option) => option.model)).toEqual(['claude-fable-5-2', 'claude-opus-5-5'])
    } finally {
      setAppConfig(DEFAULT_APP_CONFIG)
    }
  })
})

describe('usage', () => {
  it('lit les deux vues de Hermes', () => {
    expect(parseUsage({ context_used: 41_000, context_max: 1_000_000, context_percent: 4.1, avg_tps: 62.6, input: 10, output: 5, total: 15 })).toMatchObject({ contextUsed: 41_000, contextPercent: 4.1, averageTps: 62.6, inputTokens: 10, totalTokens: 15 })
    const stats = parseUsage({ input_tokens: 10, output_tokens: 5, total_tokens: 15, cache_read_tokens: 7, api_calls: 3, context_tokens: 250, context_length: 1000, context_source: 'estimate', tokens_per_s: 40, last_turn_tokens: 2 })
    expect(stats).toMatchObject({ inputTokens: 10, cacheReadTokens: 7, apiCalls: 3, contextUsed: 250, contextMax: 1000, contextPercent: 25, averageTps: 40, lastTurnTokens: 2, contextEstimated: true })
    expect(parseUsage({})).toBeNull()
  })

  it('ne perd pas un compteur absent de la trame suivante', () => {
    const first = parseUsage({ input_tokens: 10, cache_read_tokens: 7 })
    const merged = mergeUsage(first, parseUsage({ input: 20, output: 1, total: 21 }))
    expect(merged).toMatchObject({ inputTokens: 20, cacheReadTokens: 7, totalTokens: 21 })
    expect(mergeUsage(null, first)).toBe(first)
    expect(mergeUsage(first, null)).toBe(first)
  })

  it('préfère session.stats et retombe sur session.usage', async () => {
    const chat = { profile: 'nova', sessionId: 's' } as ActiveChat
    const recent = { request: vi.fn(async () => ({ total_tokens: 9 })) } as unknown as HermesClient
    expect((await loadUsage(recent, chat))?.totalTokens).toBe(9)
    expect(recent.request).toHaveBeenCalledWith('session.stats', { profile: 'nova', session_id: 's' })
    const old = { request: vi.fn(async (method: string) => { if (method === 'session.stats') throw new Error('unknown'); return { total: 4 } }) } as unknown as HermesClient
    expect((await loadUsage(old, chat))?.totalTokens).toBe(4)
  })
})

describe('pièces jointes vers Hermes', () => {
  const chat = { profile: 'nova', sessionId: 's' } as ActiveChat
  it('renvoie la référence à mettre dans le prompt', async () => {
    const client = { request: vi.fn(async () => ({ attached: true, ref_text: '@file:attachments/a.pdf' })) } as unknown as HermesClient
    await expect(attachFile(client, chat, 'a.pdf', 'data:application/pdf;base64,AA==')).resolves.toBe('@file:attachments/a.pdf')
    expect(client.request).toHaveBeenCalledWith('file.attach', { profile: 'nova', session_id: 's', name: 'a.pdf', data_url: 'data:application/pdf;base64,AA==' }, 600_000)
  })
  it('échoue si Hermes ne confirme pas', async () => {
    const client = { request: vi.fn(async () => ({ attached: false })) } as unknown as HermesClient
    await expect(attachFile(client, chat, 'a.pdf', 'data:,')).rejects.toThrow('a.pdf')
  })
})

describe('questions et accords en plein tour', () => {
  const clarify = { kind: 'clarify', prompt_id: 'c1', execution_generation: 3, question: 'Pour quel post ?', choices: ['Post A', 'Post B', ''], multi_select: false, timeout_s: 3600 }

  it('lit une question de la gateway', () => {
    expect(parsePendingPrompt('chat-orion', clarify)).toEqual({
      sessionId: 'chat-orion', kind: 'clarify', promptId: 'c1', generation: 3, question: 'Pour quel post ?',
      choices: ['Post A', 'Post B'], multiSelect: false, command: '', description: '',
    })
  })

  it('ignore une demande incomplète ou inconnue', () => {
    expect(parsePendingPrompt('chat-orion', { ...clarify, prompt_id: '' })).toBeNull()
    expect(parsePendingPrompt('chat-orion', { ...clarify, execution_generation: '3' })).toBeNull()
    expect(parsePendingPrompt('chat-orion', { ...clarify, kind: 'sudo' })).toBeNull()
    expect(parsePendingPrompt('', clarify)).toBeNull()
  })

  it('répond avec clarify.respond ou approval.respond, sur la génération de la question', async () => {
    const request = vi.fn(async () => ({ status: 'resolved', prompt_id: 'c1' }))
    const client = { request } as unknown as HermesClient
    const question = parsePendingPrompt('chat-orion', clarify)!
    await expect(answerPrompt(client, 'orion', question, 'Post B')).resolves.toBe('resolved')
    expect(request).toHaveBeenLastCalledWith('clarify.respond', { profile: 'orion', session_id: 'chat-orion', execution_generation: 3, prompt_id: 'c1', answer: 'Post B' })
    const approval = parsePendingPrompt('chat-orion', { kind: 'approval', prompt_id: 'a1', execution_generation: 3, choices: ['once', 'deny'], command: 'rm x' })!
    await answerPrompt(client, 'orion', approval, 'deny')
    expect(request).toHaveBeenLastCalledWith('approval.respond', { profile: 'orion', session_id: 'chat-orion', execution_generation: 3, prompt_id: 'a1', choice: 'deny' })
  })
})
